"""Evaluation utilities for binary churn classification.

The project treats churn as the positive class. Because the positive class is
moderately imbalanced, accuracy is not sufficient by itself. These helpers
compute metrics that separate different types of errors.

The cross-validation helper uses out-of-fold predictions. Every prediction used
for the metric table is generated by a model that was not fitted on that
observation.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

import numpy as np
import pandas as pd
from sklearn.base import clone
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    balanced_accuracy_score,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.model_selection import StratifiedKFold, cross_val_predict

from telco_churn.config import CV_N_SPLITS, CV_SHUFFLE, POSITIVE_CLASS, RANDOM_STATE


@dataclass(frozen=True)
class BinaryClassificationMetrics:
    """Container for binary classification metrics."""

    tp: int
    fn: int
    fp: int
    tn: int
    accuracy: float
    balanced_accuracy: float
    precision: float
    recall: float
    specificity: float
    f1: float
    roc_auc: float | np.floating | None
    pr_auc: float | np.floating | None
    predicted_positive_rate: float
    observed_positive_rate: float


def make_stratified_kfold(
    *,
    n_splits: int = CV_N_SPLITS,
    shuffle: bool = CV_SHUFFLE,
    random_state: int = RANDOM_STATE,
) -> StratifiedKFold:
    """Create the default stratified cross-validation splitter."""
    return StratifiedKFold(
        n_splits=n_splits,
        shuffle=shuffle,
        random_state=random_state,
    )


def compute_confusion_matrix_counts(
    y_true: pd.Series | np.ndarray,
    y_pred: pd.Series | np.ndarray,
) -> dict[str, int]:
    """Return binary confusion-matrix counts with explicit positive-first names.

    The returned dictionary follows the lecture-style visual order:

    - ``tp``: actual positive, predicted positive;
    - ``fn``: actual positive, predicted negative;
    - ``fp``: actual negative, predicted positive;
    - ``tn``: actual negative, predicted negative.

    Internally, scikit-learn's ``confusion_matrix`` with labels ``[0, 1]``
    returns the flattened order ``tn, fp, fn, tp``. This function converts that
    internal order into the positive-first order used in the notebook and
    report:

        [[TP, FN],
         [FP, TN]]
    """
    tn, fp, fn, tp = confusion_matrix(
        y_true,
        y_pred,
        labels=[0, 1],
    ).ravel()

    return {
        "tp": int(tp),
        "fn": int(fn),
        "fp": int(fp),
        "tn": int(tn),
    }


def _safe_ranking_metric(metric_function: Any, y_true: pd.Series, y_score: np.ndarray):
    """Return a ranking metric or ``None`` when it cannot be computed."""
    if len(np.unique(y_true)) < 2:
        return None

    return metric_function(y_true, y_score)


def compute_binary_classification_metrics(
    y_true: pd.Series | np.ndarray,
    y_pred: pd.Series | np.ndarray,
    *,
    y_score: pd.Series | np.ndarray | None = None,
    positive_class: int = POSITIVE_CLASS,
) -> BinaryClassificationMetrics:
    """Compute binary classification metrics for churn classification."""
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    counts = compute_confusion_matrix_counts(y_true, y_pred)
    tp = counts["tp"]
    fn = counts["fn"]
    fp = counts["fp"]
    tn = counts["tn"]

    specificity = tn / (tn + fp) if (tn + fp) > 0 else np.nan

    roc_auc = None
    pr_auc = None

    if y_score is not None:
        y_score = np.asarray(y_score)
        roc_auc = _safe_ranking_metric(roc_auc_score, y_true, y_score)
        pr_auc = _safe_ranking_metric(average_precision_score, y_true, y_score)

    return BinaryClassificationMetrics(
        tp=tp,
        fn=fn,
        fp=fp,
        tn=tn,
        accuracy=accuracy_score(y_true, y_pred),
        balanced_accuracy=balanced_accuracy_score(y_true, y_pred),
        precision=precision_score(
            y_true,
            y_pred,
            pos_label=positive_class,
            zero_division=0,
        ),
        recall=recall_score(
            y_true,
            y_pred,
            pos_label=positive_class,
            zero_division=0,
        ),
        specificity=specificity,
        f1=f1_score(
            y_true,
            y_pred,
            pos_label=positive_class,
            zero_division=0,
        ),
        roc_auc=roc_auc,
        pr_auc=pr_auc,
        predicted_positive_rate=float(np.mean(y_pred == positive_class)),
        observed_positive_rate=float(np.mean(y_true == positive_class)),
    )


def get_out_of_fold_predictions(
    *,
    estimator: Any,
    X: pd.DataFrame,
    y: pd.Series,
    cv: StratifiedKFold,
) -> tuple[np.ndarray, np.ndarray | None]:
    """Return out-of-fold hard predictions and optional positive-class scores."""
    y_pred = cross_val_predict(
        clone(estimator),
        X,
        y,
        cv=cv,
        method="predict",
        n_jobs=None,
    )

    y_score = None
    try:
        y_score = cross_val_predict(
            clone(estimator),
            X,
            y,
            cv=cv,
            method="predict_proba",
            n_jobs=None,
        )[:, 1]
    except (AttributeError, IndexError, ValueError):
        try:
            y_score = cross_val_predict(
                clone(estimator),
                X,
                y,
                cv=cv,
                method="decision_function",
                n_jobs=None,
            )
        except (AttributeError, ValueError):
            y_score = None

    return y_pred, y_score


def evaluate_estimator_cv(
    *,
    model_name: str,
    estimator: Any,
    X: pd.DataFrame,
    y: pd.Series,
    cv: StratifiedKFold | None = None,
) -> dict[str, Any]:
    """Evaluate an estimator with out-of-fold cross-validation predictions."""
    if cv is None:
        cv = make_stratified_kfold()

    y_pred, y_score = get_out_of_fold_predictions(
        estimator=estimator,
        X=X,
        y=y,
        cv=cv,
    )

    metrics = compute_binary_classification_metrics(
        y_true=y,
        y_pred=y_pred,
        y_score=y_score,
    )

    return {
        "model": model_name,
        "tp": metrics.tp,
        "fn": metrics.fn,
        "fp": metrics.fp,
        "tn": metrics.tn,
        "accuracy": metrics.accuracy,
        "balanced_accuracy": metrics.balanced_accuracy,
        "precision": metrics.precision,
        "recall": metrics.recall,
        "specificity": metrics.specificity,
        "f1": metrics.f1,
        "roc_auc": metrics.roc_auc,
        "pr_auc": metrics.pr_auc,
        "predicted_positive_rate": metrics.predicted_positive_rate,
        "observed_positive_rate": metrics.observed_positive_rate,
    }


def make_results_dataframe(results: list[dict[str, Any]]) -> pd.DataFrame:
    """Create a consistently ordered model-comparison dataframe."""
    columns = [
        "model",
        "tp",
        "fn",
        "fp",
        "tn",
        "accuracy",
        "balanced_accuracy",
        "precision",
        "recall",
        "specificity",
        "f1",
        "roc_auc",
        "pr_auc",
        "predicted_positive_rate",
        "observed_positive_rate",
    ]

    results_df = pd.DataFrame(results)

    return results_df[columns].sort_values(
        by=["balanced_accuracy", "f1"],
        ascending=False,
    )


def make_confusion_matrix_dataframe(results_df: pd.DataFrame) -> pd.DataFrame:
    """Extract lecture-ordered confusion-matrix counts from results.

    The returned order is ``model, tp, fn, fp, tn`` so that each row maps to the
    positive-first visual confusion matrix:

        [[TP, FN],
         [FP, TN]]
    """
    columns = ["model", "tp", "fn", "fp", "tn"]
    return results_df[columns].copy()


def make_metric_dataframe(results_df: pd.DataFrame) -> pd.DataFrame:
    """Extract metric columns from a model-results dataframe."""
    columns = [
        "model",
        "accuracy",
        "balanced_accuracy",
        "precision",
        "recall",
        "specificity",
        "f1",
        "roc_auc",
        "pr_auc",
        "predicted_positive_rate",
        "observed_positive_rate",
    ]
    return results_df[columns].copy()
